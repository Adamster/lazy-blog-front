def extra_book(title: str, author: str, shelf: str) -> dict:
    digest = hashlib.sha1(f"{shelf}:{author}:{title}".encode()).hexdigest()[:16]
    return {
        "author": author,
        "title": title,
        "cycleIndex": None,
        "cycleLabel": None,
        "section": None,
        "priority": "second",
        "read": False,
        "fileName": f"catalog-{digest}",
        "wordCount": None,
        "works": [],
        "bookLink": None,
        "liveLibScore": None,
        "liveLibRatingCount": 0,
        "liveLibReadCount": 0,
        "liveLibLink": None,
        "sourceGenres": [],
        "sourceRootGenres": [],
        "cover": None,
        "id": f"catalog-{digest}",
    }


def make_cycle(book: dict, series: str, volumes: list[str], shelf: str) -> None:
    first = copy.deepcopy(book)
    first.pop("seriesBooks", None)
    first["series"] = series
    first["seriesIndex"] = 1
    first["title"] = volumes[0]
    parts = [first]
    for index, title in enumerate(volumes[1:], 2):
        part = extra_book(title, book["author"], shelf)
        part["series"] = series
        part["seriesIndex"] = index
        parts.append(part)
    book["title"] = series
    book["series"] = series
    book["seriesIndex"] = 1
    book["seriesBooks"] = parts



def curate(data: list[dict]) -> tuple[list[dict], dict]:
    data = copy.deepcopy(data)
    seen = set()
    seen_titles = set()
    removed = []
    split = []
    additions = []

    # Register cycle constituents to avoid duplicating a series as a standalone
    # card. A standalone title already present elsewhere likewise wins.
    for category in data:
        for book in category["books"]:
            seen.add((norm(book["author"]), norm(book["title"])))
            if len(book.get("works") or []) <= 1:
                seen_titles.add(norm(book["title"]))
            if book.get("seriesBooks"):
                seen.add((norm(book["author"]), norm(book.get("series") or book["title"])))
                for part in book["seriesBooks"]:
                    seen_titles.add(norm(part if isinstance(part, str) else part["title"]))

    for index, category in enumerate(data):
        retained = []
        for book in category["books"]:
            title_key = norm(book["title"])
            if title_key in CUTS[index]:
                removed.append((category["label"], book["title"], "cut"))
                continue
            if index == 0 and title_key in SINGLE_NOVELS_IN_VOLUMES:
                book.pop("seriesBooks", None)
                book.pop("series", None)
                book.pop("seriesIndex", None)
                book["cycleIndex"] = None
                book["cycleLabel"] = None
            if index == 2 and title_key in CYCLE_COLLECTIONS:
                series, volumes = CYCLE_COLLECTIONS[title_key]
                make_cycle(book, series, volumes, category["label"])
                book["works"] = []
                retained.append(book)
                continue
            works = book.get("works") or []
            if index < 2 and len(works) > 1 and not book.get("seriesBooks"):
                removed.append((category["label"], book["title"], "collection"))
                for work in works:
                    work_title = work.get("title", "").strip()
                    key = (norm(book["author"]), norm(work_title))
                    if norm(work_title) not in SPLIT_WORKS or norm(work_title) in CUTS[index] or key in seen or norm(work_title) in seen_titles:
                        continue
                    item = extra_book(work_title, book["author"], category["label"])
                    item["priority"] = book["priority"]
                    item["wordCount"] = work.get("wordCount")
                    # Rating and cover of a combined edition belong to that
                    # edition, not necessarily to each work within it.
                    retained.append(item)
                    seen.add(key)
                    seen_titles.add(norm(work_title))
                    split.append((category["label"], work_title))
                continue
            if index == 0:
                book["section"] = None
            if index == 2 and book.get("series") and not book.get("seriesBooks"):
                volumes = FANTASY_SERIES.get(book["series"])
                if volumes:
                    make_cycle(book, book["series"], volumes, category["label"])
            retained.append(book)
        category["books"] = retained

    data[0]["label"] = "Проза"
    data[0]["eyebrow"] = "ПРОЗА"
    data[0]["title"] = "Проза"

    seen_titles = {
        norm(book["title"])
        for category in data
        for book in category["books"]
    }
    for category in data:
        for book in category["books"]:
            for part in book.get("seriesBooks") or []:
                seen_titles.add(norm(part if isinstance(part, str) else part["title"]))

    for key, category in zip(("prose", "scifi", "fantasy"), data):
        for row in ADDITIONS[key].strip().splitlines():
            original_title, author = (part.strip() for part in row.split("|", 1))
            title = SERIES_FIRST_BOOK.get(norm(original_title), original_title)
            match = (norm(author), norm(title))
            # A few translations use different author spelling in existing
            # files; the title check also prevents a duplicate catalogue item.
            if match in seen or norm(title) in seen_titles or norm(original_title) in seen_titles:
                continue
            book = extra_book(title, author, category["label"])
            if key == "fantasy" and original_title in FANTASY_SERIES:
                make_cycle(book, original_title, FANTASY_SERIES[original_title], category["label"])
            elif title != original_title:
                book["series"] = original_title
            category["books"].append(book)
            seen.add(match)
            seen_titles.add(norm(title))
            additions.append((category["label"], title))

    stats = {"removed": removed, "split": split, "added": additions}
    return data, stats


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    data, stats = curate(json.loads(PATH.read_text()))
    books = [book for category in data for book in category["books"]]
    counts = [len(category["books"]) for category in data]
    if sum(counts) != 1000:
        raise ValueError(f"Unexpected catalogue size: {counts}")
    if len({book["id"] for book in books}) != 1000:
        raise ValueError("Book ids are not unique")
    if len({(norm(book["author"]), norm(book["title"])) for book in books}) != 1000:
        raise ValueError("Author/title combinations are not unique")
    if any(book.get("section") for book in data[0]["books"]):
        raise ValueError("Prose still contains subcategories")
    if any(len(book.get("works") or []) > 1 for category in data for book in category["books"]):
        raise ValueError("A multi-work collection remains")
    print("Counts:", [(item["label"], len(item["books"])) for item in data])
    print("Removed:", len(stats["removed"]), "Split:", len(stats["split"]), "Added:", len(stats["added"]))
    print("Total:", sum(len(item["books"]) for item in data))
    if not args.dry_run:
        PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")


if __name__ == "__main__":
    main()
